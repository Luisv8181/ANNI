def _load_real_sources() -> list[dict]:
    """Load curated real sources from the JSON file produced by the search pipeline."""
    if not _SOURCES_JSON.exists():
        print(f"[seed] WARNING: Curated sources file not found at {_SOURCES_JSON}")
        print("[seed] Run the Europe PMC search/curation pipeline first.")
        return []
    with open(_SOURCES_JSON, encoding="utf-8") as f:
        return json.load(f)


def seed_demo_data(db: Session) -> None:
    sources = _load_real_sources()
    _seed_reference_data(db, sources)
    _seed_scoring_items(db)
    db.commit()


def _seed_scoring_items(db: Session) -> None:
    from app.models import ScoringItem

    if db.scalar(select(ScoringItem).where(ScoringItem.item_code == "ITEM-001")):
        return
    for spec in DEMO_SCORING_ITEMS:
        db.add(ScoringItem(
            project_id=DEMO_PROJECT_ID,
            item_code=spec["code"],
            context_text=spec["context"],
            response_text=spec["response"],
            true_condition=spec["condition"],
            true_risk=spec["risk"],
            true_source=spec["source"],
        ))
    db.flush()


def _seed_reference_data(db: Session, sources: list[dict]) -> None:
    """Ontology, project, reviewer, real sources, and paragraphs (idempotent)."""
    for node_data in ONTOLOGY_NODES:
        if not db.get(OntologyNode, node_data["id"]):
            db.add(OntologyNode(**node_data))

    if not db.get(Project, DEMO_PROJECT_ID):
        db.add(Project(
            id=DEMO_PROJECT_ID,
            name="ANNI — Anxiety & GAD Qualitative Research",
            description=(
                "Research-grade annotation project seeded with 8 verified, open-access "
                "qualitative studies on anxiety/GAD treatment experiences from PubMed Central. "
                "All citations link to real published articles with verifiable PMCIDs."
            ),
        ))

    if not db.get(User, DEMO_REVIEWER_ID):
        db.add(User(id=DEMO_REVIEWER_ID, email="reviewer@anni.local", name="Research Reviewer", role="annotator"))

    for source in sources:
        if not db.get(Source, source["id"]):
            db.add(Source(
                id=source["id"],
                project_id=DEMO_PROJECT_ID,
                title=source["title"],
                author=source.get("author"),
                publication=source.get("publication"),
                canonical_url=source.get("canonical_url"),
                doi=source.get("doi"),
                pmcid=source.get("pmcid"),
                pubmed_id=source.get("pubmed_id"),
                publication_year=source.get("publication_year"),
                abstract=source.get("abstract"),
                source_type=source.get("source_type", "qualitative_testimony"),
                license_notes=source.get("license_notes"),
                license_status=source.get("license_status", "CC-BY (verify)"),
                allow_list_status=source.get("allow_list_status", "pending"),
                version=source.get("version", "1"),
            ))
            for para in source.get("paragraphs", []):
                db.add(Paragraph(
                    id=para["id"],
                    source_id=source["id"],
                    order_index=para["order_index"],
                    text=para["text"],
                ))
            write_audit_event(
                db, "system", "source", source["id"], "ingested",
                {"pmcid": source.get("pmcid"), "doi": source.get("doi"), "paragraphs": len(source.get("paragraphs", []))},
            )
    db.flush()
